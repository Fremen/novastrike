export function glyphRows(ch: string): Glyph {
  return G[ch] ?? G['?'];
}

/**
 * Iterate set pixels of a glyph. Callback gets local (x, y) inside 5x7 box.
 */
export function eachGlyphPixel(
  ch: string,
  cb: (x: number, y: number) => void,
): void {
  const rows = glyphRows(ch);
  for (let y = 0; y < FONT_H; y++) {
    const row = rows[y];
    for (let x = 0; x < FONT_W; x++) {
      if (row & (1 << (FONT_W - 1 - x))) cb(x, y);
    }
  }
}
